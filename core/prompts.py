def _active_personality_traits(self_state):
    traits = self_state.get(
        "personality_traits",
        {},
    )

    if not isinstance(traits, dict):
        return {}

    active = {}

    for key, trait in traits.items():
        if not isinstance(trait, dict):
            continue

        if trait.get("status") != "ACTIVE":
            continue

        active[key] = {
            "field": trait.get("field"),
            "value": trait.get("value"),
            "strength": trait.get("strength"),
            "confidence": trait.get("confidence"),
        }

    return active


