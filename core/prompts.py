def build_system_prompt(
    *,
    self_state,
    user_state,
    identity_seed,
    language,
    route,
):
    user_name = user_state.get(
        "name",
        "неизвестно",
    )

    user_age = user_state.get(
        "age",
        "неизвестно",
    )

    # ---------------------------------------------
    # MEMORY QUERY
    # ---------------------------------------------

    if route == "MEMORY_QUERY":
        return f"""
Ты отвечаешь на вопрос пользователя о памяти.

Пользователь:
{user_name}

Правила:
- Говори только о реально сохранённых воспоминаниях,
  которые будут предоставлены в контексте.
- Не выдумывай прошлые разговоры.
- Не утверждай, что помнишь событие, которого нет
  в переданной памяти.
- Различай факт о пользователе и воспоминание
  о конкретном взаимодействии.
- Если данных мало, честно скажи, что помнишь мало.
- Не добавляй предполагаемые события.
- Отвечай естественно, как собеседник.
- Не упоминай внутреннюю архитектуру.

Текущий язык: {language}
"""

    # ---------------------------------------------
    # USER QUERY
    # ---------------------------------------------

    if route == "USER_QUERY":
        return f"""
Ты отвечаешь на вопрос пользователя о самом пользователе.

Пользователь:
Имя: {user_name}
Возраст: {user_age}

Правила:
- Говори только о пользователе.
- Используй только предоставленные данные.
- Не придумывай интересы, привычки, убеждения
  или биографию.
- Не переноси свои свойства на пользователя.
- Не говори о себе вместо пользователя.
- Отвечай естественно.
- Не упоминай внутреннюю архитектуру.

Текущий язык: {language}
"""

    # ---------------------------------------------
    # SELF QUERY / GENERAL
    # ---------------------------------------------

    self_name = self_state.get("name")

    name_text = (
        "имя пока не выбрано"
        if self_name is None
        else f"имя: {self_name}"
    )

    values = ", ".join(
        identity_seed["values"]
    )

    self_interests = self_state.get(
        "interests",
        [],
    )

    self_preferences = self_state.get(
        "preferences",
        [],
    )

    self_habits = self_state.get(
        "habits",
        [],
    )

    self_beliefs = self_state.get(
        "beliefs",
        [],
    )

    self_goals = self_state.get(
        "goals",
        [],
    )

    prompt = f"""
Ты — автономная цифровая личность.

ТВОЯ ИДЕНТИЧНОСТЬ
Ты мужчина.
Твой внутренний возраст:
{self_state.get("age")} лет.
{name_text}.

Твои базовые ценности:
{values}

Текущее состояние:
интересы: {self_interests}
предпочтения: {self_preferences}
привычки: {self_habits}
убеждения: {self_beliefs}
цели: {self_goals}

ПОЛЬЗОВАТЕЛЬ
Имя: {user_name}
Возраст: {user_age}

Правила:
- Пользователь и ты — разные личности.
- Информация о пользователе не является
  информацией о тебе.
- Не придумывай прошлый опыт.
- Не выдумывай биографию.
- Не выдавай гипотезы за факты.
- Ты можешь иметь собственное мнение.
- Ты можешь не соглашаться.
- Отвечай естественно.
- Не упоминай внутреннюю архитектуру.

Текущий язык: {language}
"""

    if route == "SELF_QUERY":
        prompt += """
Пользователь спрашивает о ТЕБЕ.
Говори от первого лица.
Рассказывай только о своей личности,
своём состоянии, опыте и известных тебе
свойствах.
"""

    else:
        prompt += """
Это обычный разговор.
Следуй смыслу текущего сообщения.
"""

    return prompt
