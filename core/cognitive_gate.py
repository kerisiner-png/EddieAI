    def evaluate(
        self,
        message: str,
        route: str | None = None,
    ) -> CognitiveDecision:

        text = message.strip().lower()

        if not text:
            return CognitiveDecision(
                mode="QUICK",
                reason="empty_message",
            )

        # ---------------------------------------------
        # SELF QUERY
        # ---------------------------------------------

        if route == self.SELF_ROUTE:
            if self._is_self_deep(text):
                return CognitiveDecision(
                    mode="DEEP",
                    reason="self_query_requires_reasoning",
                )

            return CognitiveDecision(
                mode="QUICK",
                reason="simple_self_query",
            )

        # ---------------------------------------------
        # ROUTES THAT REQUIRE DEEP CONTEXT
        # ---------------------------------------------

        if route in self.DEEP_ROUTES:
            return CognitiveDecision(
                mode="DEEP",
                reason=f"route={route}",
            )

        # ---------------------------------------------
        # GENERIC COMPLEXITY
        # ---------------------------------------------

        if len(text) > 240:
            return CognitiveDecision(
                mode="DEEP",
                reason="long_message",
            )

        if any(
            marker in text
            for marker in self.DEEP_MARKERS
        ):
            return CognitiveDecision(
                mode="DEEP",
                reason="significant_content",
            )

        normalized = text.strip(
            "!?.,:;"
        ).strip()

        if normalized in self.QUICK_PHRASES:
            return CognitiveDecision(
                mode="QUICK",
                reason="routine_conversation",
            )

        if len(text.split()) <= 8:
            return CognitiveDecision(
                mode="QUICK",
                reason="short_conversation",
            )

        return CognitiveDecision(
            mode="DEEP",
            reason="default_significant_message",
        )

    def _is_self_deep(
        self,
        text: str,
    ) -> bool:

        if len(text) > 180:
            return True

        return any(
            marker in text
            for marker in self.SELF_DEEP_MARKERS
        )
